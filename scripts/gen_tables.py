"""Generate `src/elecdef/tables/` from `data/tables/*.toml`.

Usage (from the repository root):
    uv run python scripts/gen_tables.py [--data DIR] [--out DIR]
"""

import sys
import tomllib
from decimal import ROUND_HALF_UP, Decimal, localcontext
from pathlib import Path
from typing import NoReturn

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Generated by scripts/gen_tables.py. Do not edit."
ORIGINS = ("own", "maker", "measured")
STATUSES = ("confirmed", "held")
PI = Decimal("3.141592653589793238462643383279502884197")
FOUR_DP = Decimal("0.0001")
MAX_LINE = 100


class TableError(Exception):
    """A data file the generator refuses; `main` prints it and exits 1."""


def refuse(message: str) -> NoReturn:
    """Raise a `TableError` carrying the message."""
    raise TableError(message)


def no_floats(value: object, where: str) -> None:
    """Raise when a TOML float sits anywhere inside `value`."""
    if isinstance(value, float):
        refuse(f"{where}: a float; write the figure as a string or an integer")
    if isinstance(value, dict):
        value = list(value.values())
    if isinstance(value, list):
        for item in value:
            no_floats(item, where)


def check_row(row: dict, where: str) -> None:
    """Raise unless the row has an id, a known origin and a known status."""
    for key in ("id", "origin", "status"):
        if key not in row:
            refuse(f"{where}: row {row.get('id', '?')} has no {key}")
    origin = row["origin"]
    if origin not in ORIGINS and not str(origin).startswith("open:"):
        refuse(f"{where}: row {row['id']} has origin {origin!r}")
    if row["status"] not in STATUSES:
        refuse(f"{where}: row {row['id']} has status {row['status']!r}")
    if str(origin).startswith("open:") and not row.get("licence"):
        refuse(f"{where}: row {row['id']} has an open origin and no licence")


def load(path: Path) -> dict:
    """Parse one data file and check its rows."""
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    no_floats(data, path.name)
    for row in data.get("rows", []):
        check_row(row, path.name)
    return data


def confirmed(data: dict) -> list[dict]:
    """The rows that ship."""
    return [row for row in data.get("rows", []) if row["status"] == "confirmed"]


def decimal(text: object, where: str) -> str:
    """The figure as written, after checking that it parses."""
    try:
        Decimal(str(text))
    except ArithmeticError as err:
        message = f"{where}: {text!r} is not a figure"
        raise TableError(message) from err
    return str(text)


def cell(spec: str, value: object, where: str) -> tuple[str, str]:
    """One cell as source text, with the name its import needs (empty when none)."""
    kind, _, arg = spec.partition(":")
    if kind == "int" and isinstance(value, int):
        return str(value), ""
    if kind == "str" and isinstance(value, str):
        return f'"{value}"', ""
    if kind == "unit":
        return f'Unit.{arg}("{decimal(value, where)}")', "Unit"
    if kind == "enum" and isinstance(value, str):
        return f"{arg}.{value}", arg
    refuse(f"{where}: {value!r} does not fit column {spec}")


def row_text(cells: list[str]) -> str:
    """A tuple of cells, or the one cell of a one-column table."""
    return cells[0] if len(cells) == 1 else "(" + ", ".join(cells) + ")"


def rows_const(data: dict, name: str) -> tuple[dict[str, list[str]], set[str]]:
    """The constant of a `rows` table: one tuple per confirmed row."""
    columns = data["columns"]
    lines: list[str] = []
    needs: set[str] = set()
    for row in confirmed(data):
        values = row["v"] if isinstance(row["v"], list) else [row["v"]]
        if len(values) != len(columns):
            refuse(f"{name}: row {row['id']} has {len(values)} cells")
        pairs = [cell(c, v, f"{name}:{row['id']}") for c, v in zip(columns, values, strict=True)]
        lines.append(row_text([text for text, _ in pairs]) + ",")
        needs |= {need for _, need in pairs if need}
    return {data["const"]: lines}, needs


def colours_const(data: dict, name: str) -> tuple[dict[str, list[str]], set[str]]:
    """The constant of a `colours` table: positions in order, each a tuple of `Colour`."""
    lines = []
    for number, row in enumerate(confirmed(data), 1):
        if row["id"] != number:
            refuse(f"{name}: position {row['id']} where {number} is next")
        code = row["v"]
        parts = [f"Colour.{code[i : i + 2]}" for i in range(0, len(code), 2)]
        lines.append("(" + ", ".join(parts) + (",)," if len(parts) == 1 else "),"))
    return {data["const"]: lines}, {"Colour"}


def awg_values(number: int) -> tuple[Decimal, Decimal]:
    """Diameter and area in mm and mm2, each to four places half-up."""
    with localcontext() as context:
        context.prec = 40
        exponent = Decimal(36 - number) / Decimal(39)
        diameter = (Decimal("0.127") * Decimal(92) ** exponent).quantize(FOUR_DP, ROUND_HALF_UP)
        area = (PI / 4 * diameter * diameter).quantize(FOUR_DP, ROUND_HALF_UP)
    return diameter, area


def awg_const(data: dict, name: str, series: list[dict]) -> tuple[dict[str, list[str]], set[str]]:
    """`AWG` rows `(n, diameter, area)` and `AWG_METRIC` rows `(n, smallest series size)`."""
    sizes = sorted(Decimal(str(row["v"])) for row in series)
    plain: list[str] = []
    metric: list[str] = []
    for row in confirmed(data):
        diameter, area = awg_values(row["id"])
        plain.append(f'({row["id"]}, Unit.MM("{diameter}"), Unit.MM2("{area}")),')
        size = next((s for s in sizes if s >= area), None)
        if size is None:
            refuse(f"{name}: no series size holds {area} mm2")
        metric.append(f'({row["id"]}, Unit.MM2("{size.normalize():f}")),')
    return {"AWG": plain, "AWG_METRIC": metric}, {"Unit"}


def series_rows(data_dir: Path, data: dict, name: str) -> list[dict]:
    """The confirmed rows of the table an `awg` table is measured against."""
    path = data_dir / f"{data['uses']}.toml"
    if not path.is_file():
        refuse(f"{name}: uses {data['uses']}, which is not in {data_dir}")
    return confirmed(load(path))


def credit_lines(data: dict) -> list[str]:
    """One `# Open source:` and `# Licence:` pair per distinct open origin of a shipped row."""
    pairs = sorted(
        {
            (r["origin"][5:], r["licence"])
            for r in confirmed(data)
            if r["origin"].startswith("open:")
        }
    )
    return [
        line
        for name, licence in pairs
        for line in (f"# Open source: {name}", f"# Licence: {licence}")
    ]


def module_text(name: str, data: dict, consts: dict[str, list[str]], needs: set[str]) -> str:
    """The generated module: header, credit lines, docstring, imports, then the constants."""
    doc = data["doc"]
    if len(doc) > MAX_LINE - 6:
        refuse(f"{name}: the doc line is too long")
    out = [HEADER, *credit_lines(data), f'"""{doc}"""']
    imports = ["from elecdef import Unit"] if "Unit" in needs else []
    if needs - {"Unit"}:
        imports.append("from elecdef.vocab import " + ", ".join(sorted(needs - {"Unit"})))
    out += ["", *imports] if imports else []
    for const, lines in consts.items():
        out += ["", f"{const} = (", *(f"    {line}" for line in lines), ")"]
    return "\n".join(out) + "\n"


def render(data_dir: Path, path: Path) -> tuple[str, dict[str, list[str]]]:
    """The module text of one data file, and its constants for the package index."""
    data, name = load(path), path.stem
    kind = data.get("kind")
    if kind == "rows":
        consts, needs = rows_const(data, name)
    elif kind == "colours":
        consts, needs = colours_const(data, name)
    elif kind == "awg":
        consts, needs = awg_const(data, name, series_rows(data_dir, data, name))
    else:
        refuse(f"{name}: unknown kind {kind!r}")
    return module_text(name, data, consts, needs), consts


def held_lines(data_dir: Path) -> list[str]:
    """Every held row as `name:id`, the ids of `held.toml` being written out in full."""
    lines = []
    for path in sorted(data_dir.glob("*.toml")):
        data = load(path)
        prefix = "" if path.stem == "held" else f"{path.stem}:"
        lines += [f"{prefix}{row['id']}" for row in data.get("rows", []) if row["status"] == "held"]
    return sorted(lines)


def index_text(exports: dict[str, dict[str, list[str]]]) -> str:
    """`tables/__init__.py`: every constant imported from its module and listed in `__all__`."""
    names = sorted(n for consts in exports.values() for n in consts)
    imports = [
        f"from elecdef.tables.{mod} import {', '.join(sorted(consts))}"
        for mod, consts in sorted(exports.items())
    ]
    listed = [f'    "{n}",' for n in names]
    return (
        "\n".join(
            [
                HEADER,
                '"""The data tables, generated from our own data files."""',
                "",
                *imports,
                "",
                "__all__ = [",
                *listed,
                "]",
            ]
        )
        + "\n"
    )


def build(data_dir: Path) -> dict[str, str]:
    """Every output file as `{file name: text}`; raises `TableError` before anything is written."""
    files: dict[str, str] = {}
    exports: dict[str, dict[str, list[str]]] = {}
    for path in sorted(data_dir.glob("*.toml")):
        if path.stem == "held":
            load(path)
            continue
        files[f"{path.stem}.py"], exports[path.stem] = render(data_dir, path)
    files["__init__.py"] = index_text(exports)
    files["HELD.txt"] = "".join(f"{line}\n" for line in held_lines(data_dir))
    return files


def main(argv: list[str]) -> int:
    """Write the tables; exit 1 with the reason on stderr when a data file is refused."""
    args = dict(zip(argv[::2], argv[1::2], strict=False))
    data_dir = Path(args.get("--data", ROOT / "data" / "tables"))
    out_dir = Path(args.get("--out", ROOT / "src" / "elecdef" / "tables"))
    try:
        files = build(data_dir)
    except TableError as err:
        sys.stderr.write(f"gen_tables: {err}\n")
        return 1
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out_dir / name).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
