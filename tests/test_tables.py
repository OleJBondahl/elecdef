"""E14 gate: tables have the header, no marked word, no held row, and regenerate equal."""

import ast
import importlib
import re
import subprocess
import sys
import tomllib
from decimal import Decimal
from enum import Enum
from pathlib import Path

import family
import pytest

from elecdef import Quantity

GENERATOR = family.ROOT / "scripts" / "gen_tables.py"
DATA = family.ROOT / "data" / "tables"
TABLES = family.ROOT / "src" / "elecdef" / "tables"
HEADER = "# Generated by scripts/gen_tables.py. Do not edit."
MARKED = re.compile(r"http|source|verified", re.IGNORECASE)
GOOD = '    { id = "1", v = "1", origin = "own", status = "confirmed" },\n'


def generate(data: Path, out: Path) -> subprocess.CompletedProcess[str]:
    """Run the generator on `data` into `out`."""
    argv = [sys.executable, str(GENERATOR), "--data", str(data), "--out", str(out)]
    return subprocess.run(argv, capture_output=True, text=True, check=False)  # noqa: S603 - fixed argv


def one_table(tmp_path: Path, rows: str, extra: str = "") -> Path:
    """A data folder holding one rows table with the given row lines."""
    data = tmp_path / "data"
    data.mkdir()
    text = f'kind = "rows"\ndoc = "A test table."\nconst = "T"\ncolumns = ["unit:MM2"]\n{extra}'
    (data / "t.toml").write_text(f"{text}rows = [\n{rows}]\n", encoding="utf-8")
    return data


def leaves(value: object) -> set[str]:
    """Every leaf of a constant as text: enum member names, ints, figures and strings."""
    if isinstance(value, tuple):
        return set().union(*(leaves(item) for item in value))
    if isinstance(value, Enum):
        return {value.name}
    if isinstance(value, Quantity):
        return {str(value.value)}
    return {str(value)}


def modules() -> list[Path]:
    """Every generated module, the package index included."""
    return sorted(TABLES.glob("*.py"))


def test_tables_exist():
    assert len(modules()) >= 10
    assert (TABLES / "HELD.txt").is_file()


@pytest.mark.parametrize("path", modules(), ids=lambda p: p.name)
def test_header(path):
    assert path.read_text(encoding="utf-8").splitlines()[0] == HEADER


@pytest.mark.parametrize("path", modules(), ids=lambda p: p.name)
def test_no_marked_words(path):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    strings = [
        n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)
    ]
    assert not [s for s in strings if MARKED.search(s)]


def test_held_rows_are_absent():
    held = (TABLES / "HELD.txt").read_text(encoding="utf-8").split()
    assert held
    for line in held:
        name, _, row_id = line.partition(":")
        if not (TABLES / f"{name}.py").is_file():
            continue
        module = importlib.import_module(f"elecdef.tables.{name}")
        shipped = set().union(*(leaves(v) for k, v in vars(module).items() if k.isupper()))
        row = next(
            r
            for r in tomllib.loads((DATA / f"{name}.toml").read_text())["rows"]
            if str(r["id"]) == row_id
        )
        assert row["status"] == "held"
        assert row_id not in shipped, line


def test_held_list_matches_the_data():
    wanted = []
    for path in sorted(DATA.glob("*.toml")):
        rows = tomllib.loads(path.read_text(encoding="utf-8"))["rows"]
        prefix = "" if path.stem == "held" else f"{path.stem}:"
        wanted += [f"{prefix}{r['id']}" for r in rows if r["status"] == "held"]
    assert (TABLES / "HELD.txt").read_text(encoding="utf-8").split() == sorted(wanted)


def test_regeneration_is_byte_equal(tmp_path):
    done = generate(DATA, tmp_path)
    assert done.returncode == 0, done.stderr
    made = {p.name: p.read_bytes() for p in tmp_path.iterdir()}
    shipped = {p.name: p.read_bytes() for p in TABLES.iterdir() if p.is_file()}
    assert made == shipped


def test_awg_values():
    awg = importlib.import_module("elecdef.tables").AWG
    by_n = {n: (d.value, a.value) for n, d, a in awg}
    assert by_n[-3][0] == Decimal("11.6840")
    assert by_n[10] == (Decimal("2.5882"), Decimal("5.2612"))
    assert len(awg) == 44


def test_generator_accepts_a_good_row(tmp_path):
    done = generate(one_table(tmp_path, GOOD), tmp_path / "out")
    assert done.returncode == 0, done.stderr
    assert 'Unit.MM2("1")' in (tmp_path / "out" / "t.py").read_text(encoding="utf-8")


@pytest.mark.parametrize(
    ("row", "word"),
    [
        ('    { id = "1", v = "1", status = "confirmed" },\n', "origin"),
        ('    { id = "1", v = "1", origin = "own" },\n', "status"),
        ('    { id = "1", v = "1", origin = "a standard", status = "confirmed" },\n', "origin"),
        ('    { id = "1", v = "1", origin = "own", status = "maybe" },\n', "status"),
        ('    { id = "1", v = 0.5, origin = "own", status = "confirmed" },\n', "float"),
        ('    { id = "1", v = "x", origin = "own", status = "confirmed" },\n', "figure"),
        ('    { id = "1", v = "1", origin = "open:Foo", status = "confirmed" },\n', "licence"),
    ],
)
def test_generator_exits_one(tmp_path, row, word):
    done = generate(one_table(tmp_path, row), tmp_path / "out")
    assert done.returncode == 1
    assert word in done.stderr
    assert not (tmp_path / "out").exists()


def test_generator_writes_the_open_header(tmp_path):
    row = '    { id = "1", v = "1", origin = "open:Foo", licence = "MIT", status = "confirmed" },\n'
    assert generate(one_table(tmp_path, row), tmp_path / "out").returncode == 0
    lines = (tmp_path / "out" / "t.py").read_text(encoding="utf-8").splitlines()
    assert lines[:3] == [HEADER, "# Open source: Foo", "# Licence: MIT"]


def test_generator_skips_a_held_row(tmp_path):
    held = '    { id = "9", v = "9", origin = "own", status = "held" },\n'
    assert generate(one_table(tmp_path, GOOD + held), tmp_path / "out").returncode == 0
    assert '"9"' not in (tmp_path / "out" / "t.py").read_text(encoding="utf-8")
    assert (tmp_path / "out" / "HELD.txt").read_text(encoding="utf-8") == "t:9\n"
